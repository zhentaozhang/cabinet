/**
 * Correlation identifiers.
 *
 * Pure string handling with no runtime imports: `src/proxy.ts` runs on the edge
 * runtime and must be able to mint and forward identifiers without pulling in
 * anything Node-specific.
 */

export const REQUEST_ID_HEADER = "x-request-id";
export const REQUEST_PATH_HEADER = "x-request-path";
export const REQUEST_METHOD_HEADER = "x-request-method";

/**
 * Accepted inbound identifiers. Deliberately strict: an id is written into
 * every log line, so the charset is bounded to keep the field parseable and to
 * stop a caller from smuggling formatting into the logs.
 */
const ID_PATTERN = /^[A-Za-z0-9._:-]{8,96}$/;

function hex(byte: number): string {
  return byte.toString(16).padStart(2, "0");
}

/** `r_` + 16 hex characters, ~64 bits of entropy per request. */
export function newRequestId(): string {
  const bytes = new Uint8Array(8);

  const cryptoApi = globalThis.crypto;
  if (cryptoApi && typeof cryptoApi.getRandomValues === "function") {
    cryptoApi.getRandomValues(bytes);
  } else {
    for (let index = 0; index < bytes.length; index += 1) {
      bytes[index] = Math.floor(Math.random() * 256);
    }
  }

  let out = "r_";
  for (let index = 0; index < bytes.length; index += 1) {
    out += hex(bytes[index] ?? 0);
  }
  return out;
}

export function sanitizeRequestId(value: string | null | undefined): string | null {
  if (!value) return null;
  const trimmed = value.trim();
  return ID_PATTERN.test(trimmed) ? trimmed : null;
}

/**
 * Identifiers generated by `src/lib/ids.ts` (`tsk_9fX…`), UUIDs and pure
 * numeric ids in a path are replaced with `:id`, so a route keeps a bounded
 * cardinality regardless of how many rows exist.
 */
const ID_SEGMENT = new RegExp(
  [
    "^[a-z]{2,5}_[A-Za-z0-9]{6,}$",
    "^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$",
    "^\\d{4,}$",
  ].join("|"),
  "i",
);

const MAX_SEGMENTS = 8;
const MAX_PATH = 200;

export function templateOfPath(path: string): string {
  const clean = path.split("?")[0] ?? "/";
  const segments = clean
    .slice(0, MAX_PATH)
    .split("/")
    .slice(0, MAX_SEGMENTS)
    .map((segment) => (ID_SEGMENT.test(segment) ? ":id" : segment));

  const template = segments.join("/");
  return template === "" ? "/" : template;
}
